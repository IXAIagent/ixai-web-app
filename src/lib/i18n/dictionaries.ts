function createPack(
  basePack: TranslationPack,
  overrides: Partial<Record<I18NNamespace, NamespaceDictionary>>,
): TranslationPack {
  return I18N_NAMESPACES.reduce((nextPack, namespace) => {
    nextPack[namespace] = {
      ...basePack[namespace],
      ...(overrides[namespace] ?? {}),
    };
    return nextPack;
  }, {} as TranslationPack);
}

